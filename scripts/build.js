import { execSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, '..')
const clientDist = path.join(rootDir, 'client', 'dist')
const rootDist = path.join(rootDir, 'dist')

const isWindows = process.platform === 'win32'
const npmCmd = isWindows ? 'npm.cmd' : 'npm'

console.log('Building client with Vite...')
execSync(`${npmCmd} run build --workspace client`, {
  stdio: 'inherit',
  cwd: rootDir,
})

if (fs.existsSync(clientDist)) {
  console.log('Copying build output to dist/ for Vercel and Render deployment...')
  fs.rmSync(rootDist, { recursive: true, force: true })
  fs.cpSync(clientDist, rootDist, { recursive: true })
  console.log('✓ Successfully populated dist/ at root directory.')
} else {
  console.error('Error: client/dist was not generated by the build.')
  process.exit(1)
}
